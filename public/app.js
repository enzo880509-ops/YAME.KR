function resetHomeScrollPosition() {
  if (document.body.dataset.page !== 'home' || window.location.hash) return;
  window.scrollTo(0, 0);
}

function setupInitialScrollPosition() {
  if (document.body.dataset.page !== 'home' || window.location.hash) return;

  if ('scrollRestoration' in history) history.scrollRestoration = 'manual';

  const reset = () => resetHomeScrollPosition();
  reset();
  window.requestAnimationFrame(reset);
  window.addEventListener('load', () => window.requestAnimationFrame(reset), { once: true });
  window.addEventListener('pageshow', () => {
    reset();
    window.requestAnimationFrame(reset);
    window.setTimeout(reset, 100);
  });
}

let introSplashRunId = 0;

function setupIntroSplash() {
  const splash = document.querySelector('[data-intro-splash]');
  const image = splash?.querySelector('[data-intro-image]');
  if (!splash || !image) return;

  // The GIF is configured to play once (2.8s). Start the fade slightly
  // before its final frame so the black veil finishes at the same moment.
  const introAnimationDuration = Number(splash.dataset.duration) || 2800;
  const introFadeDuration = Math.min(280, introAnimationDuration);
  const runId = ++introSplashRunId;
  let dismissalTimer;
  let fallbackTimer;
  const dismiss = () => {
    if (runId !== introSplashRunId || !splash.isConnected) return;
    if (splash.classList.contains('is-leaving')) return;
    window.clearTimeout(dismissalTimer);
    window.clearTimeout(fallbackTimer);
    splash.classList.add('is-leaving');
    document.body.classList.remove('has-intro-splash');
    resetHomeScrollPosition();
    window.setTimeout(() => {
      if (runId !== introSplashRunId || !splash.isConnected) return;
      splash.hidden = true;
      splash.classList.remove('is-leaving');
      image.removeAttribute('src');
    }, 300);
  };

  image.addEventListener('load', () => {
    dismissalTimer = window.setTimeout(
      dismiss,
      Math.max(0, introAnimationDuration - introFadeDuration)
    );
  }, { once: true });
  image.addEventListener('error', dismiss, { once: true });

  splash.classList.remove('is-leaving');
  splash.hidden = false;
  document.body.classList.add('has-intro-splash');
  image.src = `${image.dataset.src}?play=${Date.now()}`;
  fallbackTimer = window.setTimeout(dismiss, introAnimationDuration + 1000);
}

function setupMenu() {
  if (activeMenuKeyHandler) document.removeEventListener('keydown', activeMenuKeyHandler);
  const button = document.querySelector('.menu-button');
  const menu = document.querySelector('.menu-panel');
  if (!button || !menu) return;
  const menuGif = menu.querySelector('[data-menu-gif]');
  const menuGifPreload = menuGif ? new Image() : null;
  if (menuGifPreload) menuGifPreload.src = menuGif.dataset.src;

  const startMenuGif = () => {
    if (!menuGif || menuGif.hasAttribute('src')) return;
    menuGif.src = menuGif.dataset.src;
  };

  const stopMenuGif = () => {
    if (!menuGif) return;
    menuGif.removeAttribute('src');
  };

  const closeMenu = () => {
    button.setAttribute('aria-expanded', 'false');
    button.setAttribute('aria-label', 'Open menu');
    menu.classList.remove('is-open');
    stopMenuGif();
  };

  button.addEventListener('click', () => {
    const willOpen = button.getAttribute('aria-expanded') !== 'true';
    button.setAttribute('aria-expanded', String(willOpen));
    button.setAttribute('aria-label', willOpen ? 'Close menu' : 'Open menu');
    if (willOpen) {
      // Start the GIF before revealing the panel so its first frame follows the open action.
      startMenuGif();
      menu.classList.add('is-open');
    } else {
      stopMenuGif();
      menu.classList.remove('is-open');
    }
  });

  menu.addEventListener('click', closeMenu);
  activeMenuKeyHandler = (event) => {
    if (event.key === 'Escape') closeMenu();
  };
  document.addEventListener('keydown', activeMenuKeyHandler);
}

function setupCarousel() {
  const carousel = document.querySelector('.featured');
  if (!carousel) return;
  const track = carousel.querySelector('.carousel-track');
  const slides = [...track.querySelectorAll('.feature-slide')];
  const previous = carousel.querySelector('[data-slide-prev]');
  const next = carousel.querySelector('[data-slide-next]');
  const dots = [...carousel.querySelectorAll('[data-slide-to]')];
  const number = carousel.querySelector('[data-slide-number]');
  const status = carousel.querySelector('[data-carousel-status]');
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  const desktopCarousel = window.matchMedia('(min-width: 760px)');
  let active = 0;
  let target = null;
  let settleTimer;
  let pointer = null;
  let suppressClickUntil = 0;

  const position = index => {
    const slideStart = slides[index].offsetLeft - slides[0].offsetLeft;
    if (!desktopCarousel.matches) return slideStart;
    return Math.min(slideStart, Math.max(0, track.scrollWidth - track.clientWidth));
  };
  const nearest = () => {
    const desktopEnd = track.scrollWidth - track.clientWidth;
    if (desktopCarousel.matches && Math.abs(desktopEnd - track.scrollLeft) < 2) return slides.length - 1;
    return slides.reduce((best, _, index) =>
      Math.abs(position(index) - track.scrollLeft) < Math.abs(position(best) - track.scrollLeft) ? index : best, 0);
  };

  function update(index) {
    const changed = active !== index;
    active = index;
    previous.disabled = index === 0;
    next.disabled = index === slides.length - 1;
    number.textContent = String(index + 1).padStart(2, '0');
    dots.forEach((dot, i) => {
      if (i === index) dot.setAttribute('aria-current', 'true');
      else dot.removeAttribute('aria-current');
    });
    if (changed) status.textContent = `Featured article ${slides[index].getAttribute('aria-label')}.`;
  }

  function goTo(index, animate = true) {
    target = Math.max(0, Math.min(slides.length - 1, index));
    update(target);
    track.scrollTo({ left: position(target), behavior: animate && !reducedMotion.matches ? 'smooth' : 'auto' });
  }

  previous.addEventListener('click', () => goTo((target ?? nearest()) - 1));
  next.addEventListener('click', () => goTo((target ?? nearest()) + 1));
  dots.forEach(dot => dot.addEventListener('click', () => goTo(Number(dot.dataset.slideTo))));

  track.addEventListener('keydown', event => {
    if (event.altKey || event.ctrlKey || event.metaKey) return;
    const index = target ?? nearest();
    const destinations = { ArrowLeft: index - 1, ArrowRight: index + 1, Home: 0, End: slides.length - 1 };
    if (!(event.key in destinations)) return;
    event.preventDefault();
    goTo(destinations[event.key]);
  });

  track.addEventListener('scroll', () => {
    clearTimeout(settleTimer);
    if (target === null) update(nearest());
    settleTimer = setTimeout(() => {
      if (pointer?.dragging) return;
      target = null;
      update(nearest());
    }, 140);
  }, { passive: true });

  track.addEventListener('pointerdown', event => {
    // Native touch scrolling preserves vertical page movement and swipe inertia.
    if (event.pointerType === 'touch' || event.button !== 0) return;
    clearTimeout(settleTimer);
    target = null;
    suppressClickUntil = 0;
    pointer = { id: event.pointerId, x: event.clientX, y: event.clientY, scroll: track.scrollLeft, dragging: false };
  });
  track.addEventListener('pointermove', event => {
    if (!pointer || pointer.id !== event.pointerId) return;
    const dx = event.clientX - pointer.x;
    const dy = event.clientY - pointer.y;
    if (!pointer.dragging) {
      if (Math.abs(dx) < 8 || Math.abs(dx) < Math.abs(dy)) return;
      pointer.dragging = true;
      track.classList.add('is-dragging');
      track.setPointerCapture(event.pointerId);
    }
    event.preventDefault();
    track.scrollLeft = pointer.scroll - dx;
  });
  function endDrag(event) {
    if (!pointer || pointer.id !== event.pointerId) return;
    const dragged = pointer.dragging;
    pointer = null;
    track.classList.remove('is-dragging');
    if (track.hasPointerCapture(event.pointerId)) track.releasePointerCapture(event.pointerId);
    if (dragged) {
      suppressClickUntil = performance.now() + 350;
      goTo(nearest());
    }
  }
  track.addEventListener('pointerup', endDrag);
  track.addEventListener('pointercancel', endDrag);
  track.addEventListener('lostpointercapture', endDrag);
  track.addEventListener('pointerleave', event => { if (pointer && !pointer.dragging) endDrag(event); });
  track.addEventListener('click', event => {
    if (performance.now() < suppressClickUntil) {
      event.preventDefault();
      event.stopPropagation();
    }
  }, true);
  track.addEventListener('dragstart', event => event.preventDefault());
  track.addEventListener('focusin', event => {
    const slide = event.target.closest('.feature-slide');
    if (slide && !pointer) goTo(slides.indexOf(slide));
  });

  if ('ResizeObserver' in window) {
    new ResizeObserver(() => goTo(active, false)).observe(track);
  } else {
    window.addEventListener('resize', () => goTo(active, false));
  }
  update(0);
}

