  intro.className = 'search-intro';
  intro.hidden = true;
  intro.setAttribute('aria-hidden', 'true');
  intro.innerHTML = '<img data-search-intro-image data-src="/assets/yame-search.gif" alt="" width="1080" height="1080" />';
