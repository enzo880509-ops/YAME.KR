function setupGlobalPipDragging(root) {
  const pipWindow = root.querySelector('.pip-window');
  const edgeTabs = [...root.querySelectorAll('[data-pip-edge-tab]')];
  const backdrop = root.querySelector('[data-pip-backdrop]');
  const closeHint = root.querySelector('[data-pip-close-hint]');
  let dragOriginX = 0;
  let dragOriginY = 0;
  let pointerOriginX = 0;
  let pointerOriginY = 0;
  let dragging = false;
  let edgePointer = null;
  let edgeWasDragged = false;
  let activeSide = 'right';

  const setExpanded = (expanded) => {
    pipWindow.classList.toggle('is-expanded', expanded);
    if (expanded) pipWindow.removeAttribute('data-pip-closed');
    const mobile = window.matchMedia('(max-width: 759px)').matches;
    const showBackdrop = expanded;
    const showCloseHint = expanded;
    closeHint.hidden = !showCloseHint;
    const closeAction = closeHint.querySelector('[data-close-hint-action]');
    if (closeAction) closeAction.textContent = mobile ? 'TAP TO' : 'CLICK TO';
    closeHint.setAttribute('aria-label', `${mobile ? 'Tap' : 'Click'} to close Walkman player`);
    closeHint.classList.toggle('pip-close-hint--left', activeSide === 'right');
    closeHint.classList.toggle('pip-close-hint--right', activeSide === 'left');
    if (showCloseHint) {
      window.requestAnimationFrame(() => {
        const rect = pipWindow.getBoundingClientRect();
        closeHint.style.top = `${rect.top + rect.height / 2}px`;
        if (mobile) {
          closeHint.style.left = '';
          closeHint.style.right = '';
        } else {
          const hintWidth = closeHint.getBoundingClientRect().width;
          const hintLeft = activeSide === 'right' ? rect.left - hintWidth - 12 : rect.right + 12;
          closeHint.style.left = `${Math.max(8, Math.min(window.innerWidth - hintWidth - 8, hintLeft))}px`;
          closeHint.style.right = 'auto';
        }
      });
    }
    if (showBackdrop) {
      backdrop.hidden = false;
      window.requestAnimationFrame(() => backdrop.classList.add('is-visible'));
    } else {
      backdrop.classList.remove('is-visible');
      window.setTimeout(() => {
        if (!backdrop.classList.contains('is-visible')) backdrop.hidden = true;
      }, 180);
    }
    backdrop.hidden = !showBackdrop && !backdrop.classList.contains('is-visible');
    backdrop.setAttribute('aria-hidden', String(backdrop.hidden));
  };

  const collapseToSide = (side = activeSide) => {
    activeSide = side;
    pipWindow.style.left = '';
    pipWindow.style.top = '';
    pipWindow.style.right = '';
    pipWindow.style.bottom = '';
    pipWindow.classList.remove('is-hidden-left', 'is-hidden-right');
    pipWindow.classList.add(side === 'left' ? 'is-hidden-left' : 'is-hidden-right');
    pipWindow.dataset.pipClosed = 'true';
    edgeTabs.forEach((tab) => { tab.hidden = tab.dataset.pipEdgeTab !== side; });
    setExpanded(false);
  };

  closeHint.addEventListener('click', () => collapseToSide(activeSide));

  // Start as the slim edge tab. The player iframe stays mounted so audio can
  // continue while the PIP is tucked away.
  collapseToSide('right');

  pipWindow.addEventListener('pointerdown', (event) => {
    // On phones the expanded player stays anchored at its fixed screen position.
    if (window.matchMedia('(max-width: 759px)').matches) return;
    if (event.target.closest('button, input, iframe, [data-device-playlist-panel]')) return;
    if (event.pointerType === 'mouse' && event.button !== 0) return;
    const rect = pipWindow.getBoundingClientRect();
    pipWindow.classList.remove('is-hidden-left', 'is-hidden-right');
    pipWindow.removeAttribute('data-pip-closed');
    setExpanded(false);
    edgeTabs.forEach((tab) => { tab.hidden = true; });
    dragOriginX = rect.left;
    dragOriginY = rect.top;
    pointerOriginX = event.clientX;
    pointerOriginY = event.clientY;
    pipWindow.style.left = `${rect.left}px`;
    pipWindow.style.top = `${rect.top}px`;
    pipWindow.style.right = 'auto';
    pipWindow.style.bottom = 'auto';
    dragging = true;
    pipWindow.classList.add('is-dragging');
    pipWindow.setPointerCapture(event.pointerId);
    event.preventDefault();
  });
  pipWindow.addEventListener('pointermove', (event) => {
    if (!dragging) return;
    const rect = pipWindow.getBoundingClientRect();
    const left = Math.min(Math.max(0, dragOriginX + event.clientX - pointerOriginX), window.innerWidth - rect.width);
    const top = Math.min(Math.max(0, dragOriginY + event.clientY - pointerOriginY), window.innerHeight - rect.height);
    pipWindow.style.left = `${left}px`;
    pipWindow.style.top = `${top}px`;
  });
  const stopDragging = () => {
    if (!dragging) return;
    dragging = false;
    pipWindow.classList.remove('is-dragging');
    const rect = pipWindow.getBoundingClientRect();
    const edgeY = Math.min(window.innerHeight - 48, Math.max(48, rect.top + rect.height / 2));
    document.documentElement.style.setProperty('--yame-pip-edge-y', `${edgeY}px`);
    if (rect.left <= 36) {
      activeSide = 'left';
      pipWindow.style.left = '0px';
      pipWindow.style.right = 'auto';
      pipWindow.classList.add('is-hidden-left');
      pipWindow.dataset.pipClosed = 'true';
      edgeTabs.forEach((tab) => { tab.hidden = tab.dataset.pipEdgeTab !== 'left'; });
      setExpanded(false);
    } else if (window.innerWidth - rect.right <= 36) {
      activeSide = 'right';
      pipWindow.style.left = `${window.innerWidth - rect.width}px`;
      pipWindow.style.right = 'auto';
      pipWindow.classList.add('is-hidden-right');
      pipWindow.dataset.pipClosed = 'true';
      edgeTabs.forEach((tab) => { tab.hidden = tab.dataset.pipEdgeTab !== 'right'; });
      setExpanded(false);
    }
  };
  pipWindow.addEventListener('pointerup', stopDragging);
  pipWindow.addEventListener('pointercancel', stopDragging);

  const restoreWindow = (tab) => {
    const side = tab.dataset.pipEdgeTab;
    activeSide = side;
    const barRect = tab.getBoundingClientRect();
    const rect = pipWindow.getBoundingClientRect();
    const center = barRect.top + barRect.height / 2;
    const top = Math.min(Math.max(0, center - rect.height / 2), window.innerHeight - rect.height);
    const restoredLeft = side === 'left' ? 0 : window.innerWidth - rect.width;
    pipWindow.style.left = `${restoredLeft}px`;
    pipWindow.style.right = 'auto';
    if (window.matchMedia('(max-width: 759px)').matches) {
      pipWindow.style.top = 'auto';
      pipWindow.style.bottom = '8vh';
    } else {
      pipWindow.style.top = `${top}px`;
      pipWindow.style.bottom = 'auto';
    }
    pipWindow.classList.remove('is-hidden-left', 'is-hidden-right');
    pipWindow.removeAttribute('data-pip-closed');
    setExpanded(true);
    edgeTabs.forEach((edgeTab) => { edgeTab.hidden = true; });
  };

  edgeTabs.forEach((tab) => {
    tab.addEventListener('pointerdown', (event) => {
      if (window.matchMedia('(max-width: 759px)').matches) return;
      if (event.pointerType === 'mouse' && event.button !== 0) return;
      const rect = tab.getBoundingClientRect();
      edgePointer = { id: event.pointerId, startY: event.clientY, centerY: rect.top + rect.height / 2, moved: false };
      edgeWasDragged = false;
      tab.setPointerCapture(event.pointerId);
      event.preventDefault();
    });
    tab.addEventListener('pointermove', (event) => {
      if (window.matchMedia('(max-width: 759px)').matches) return;
      if (!edgePointer || edgePointer.id !== event.pointerId) return;
      const delta = event.clientY - edgePointer.startY;
      if (Math.abs(delta) > 4) edgePointer.moved = true;
      const halfHeight = tab.getBoundingClientRect().height / 2;
      const center = Math.min(Math.max(halfHeight, edgePointer.centerY + delta), window.innerHeight - halfHeight);
      document.documentElement.style.setProperty('--yame-pip-edge-y', `${center}px`);
    });
    tab.addEventListener('pointerup', (event) => {
      if (!edgePointer || edgePointer.id !== event.pointerId) return;
      edgeWasDragged = edgePointer.moved;
      edgePointer = null;
    });
    tab.addEventListener('pointercancel', () => { edgePointer = null; });
    tab.addEventListener('click', () => {
      if (edgeWasDragged) { edgeWasDragged = false; return; }
      restoreWindow(tab);
    });
  });
  backdrop.addEventListener('click', () => collapseToSide(activeSide));
  window.addEventListener('resize', () => {
    if (pipWindow.hasAttribute('data-pip-closed')) {
      collapseToSide(activeSide);
      return;
    }
    const rect = pipWindow.getBoundingClientRect();
    const mobile = window.matchMedia('(max-width: 759px)').matches;
    const left = activeSide === 'left' ? 0 : Math.max(0, window.innerWidth - rect.width);
    pipWindow.style.left = `${left}px`;
    pipWindow.style.right = 'auto';
    if (mobile) {
      pipWindow.style.top = 'auto';
      pipWindow.style.bottom = '8vh';
    } else {
      pipWindow.style.top = `${Math.min(Math.max(0, rect.top), Math.max(0, window.innerHeight - rect.height))}px`;
      pipWindow.style.bottom = 'auto';
    }
    setExpanded(true);
  }, { passive: true });
}

function setupPersistentPipNavigation() {
  const pip = document.querySelector('[data-global-walkman-pip]');
  const shell = document.querySelector('#yame-site-shell');
  if (!pip || !shell || walkmanExcludedPath()) return;

  if ('scrollRestoration' in history) history.scrollRestoration = 'manual';
  history.replaceState({ ...(history.state || {}), yamePersistentPip: true, scrollY: window.scrollY }, '', window.location.href);
  let scrollSaveFrame = 0;
  window.addEventListener('scroll', () => {
    if (scrollSaveFrame) return;
    scrollSaveFrame = window.requestAnimationFrame(() => {
      scrollSaveFrame = 0;
      history.replaceState({ ...(history.state || {}), yamePersistentPip: true, scrollY: window.scrollY }, '', window.location.href);
    });
  }, { passive: true });

  const renderRoute = async (url, { push = false, scrollY = 0 } = {}) => {
    if (walkmanExcludedPath(url.pathname)) {
      window.location.assign(url.href);
      return false;
    }
    const response = await fetch(url.href, { headers: { Accept: 'text/html' } });
    if (!response.ok) throw new Error(`Page request failed: ${response.status}`);
    const nextDocument = new DOMParser().parseFromString(await response.text(), 'text/html');
    const nextMain = nextDocument.querySelector('main');
    if (!nextMain) throw new Error('The destination page has no main content.');

    // Keep the live YouTube iframe outside the replaceable route shell. If a
    // later markup change accidentally nests it in the shell, hoist it before
    // replacing route content so navigation cannot unload the playing frame.
    if (pip.parentElement === shell) document.body.append(pip);

    nextDocument.querySelectorAll('[href], [src], [poster]').forEach((element) => {
      for (const attribute of ['href', 'src', 'poster']) {
        const value = element.getAttribute(attribute);
        if (!value || value.startsWith('#') || value.startsWith('data:')) continue;
        try { element.setAttribute(attribute, new URL(value, url.href).href); } catch {}
      }
    });

    if (push) {
      history.replaceState({ ...(history.state || {}), yamePersistentPip: true, scrollY: window.scrollY }, '', window.location.href);
      history.pushState({ yamePersistentPip: true, scrollY: 0 }, '', url.href);
    }

    document.querySelectorAll('.search-overlay, .search-intro, .gallery-lightbox').forEach((overlay) => overlay.remove());
    document.body.classList.remove('search-is-open', 'gallery-is-open', 'has-intro-splash');
    const newNodes = Array.from(nextDocument.body.childNodes)
      .filter((node) => !(node.nodeType === Node.ELEMENT_NODE && node.tagName === 'SCRIPT'))
      .map((node) => document.importNode(node, true));
    shell.replaceChildren(...newNodes);
    Array.from(document.body.attributes).forEach((attribute) => document.body.removeAttribute(attribute.name));
    Array.from(nextDocument.body.attributes).forEach((attribute) => document.body.setAttribute(attribute.name, attribute.value));
    document.title = nextDocument.title;
    document.documentElement.lang = nextDocument.documentElement.lang || 'en';
    const currentDescription = document.querySelector('meta[name="description"]');
    const nextDescription = nextDocument.querySelector('meta[name="description"]');
    if (currentDescription && nextDescription) currentDescription.content = nextDescription.content;

    setupMenu();
    setupCarousel();
    setupReviewFilters();
    setupLanguageSelector();
    setupScrollReveal();
    const requestedLanguage = url.searchParams.get('lang');
    const nextLanguage = requestedLanguage === 'kr' ? 'kr' : (requestedLanguage === 'en' ? 'en' : activeLanguage);
    setupSearch();
    applyLanguage(nextLanguage);

    // The home intro GIF is part of the home-route entry experience. Since
    // route changes keep this document alive, explicitly restart it whenever
    // the home page is restored through client-side navigation or history.
    if (nextDocument.body.dataset.page === 'home') setupIntroSplash();

    if (url.hash) {
      requestAnimationFrame(() => document.getElementById(decodeURIComponent(url.hash.slice(1)))?.scrollIntoView());
    } else {
      window.scrollTo(0, scrollY);
    }
    return true;
  };

  document.addEventListener('click', (event) => {
    if (event.defaultPrevented || (event.button !== 0 && event.detail !== 0) || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    const link = event.target?.closest?.('a[href]');
    if (!link || link.target || link.hasAttribute('download') || link.relList.contains('external')) return;
    const targetUrl = new URL(link.href, window.location.href);
    if (targetUrl.origin !== window.location.origin || targetUrl.protocol !== 'http:' && targetUrl.protocol !== 'https:') return;
    if (walkmanExcludedPath(targetUrl.pathname)) return;
    if (targetUrl.href === window.location.href) { event.preventDefault(); return; }
    if (targetUrl.pathname === window.location.pathname && targetUrl.search === window.location.search && targetUrl.hash) return;
    event.preventDefault();
    renderRoute(targetUrl, { push: true }).catch((error) => {
      // A full document navigation destroys the live YouTube iframe. Preserve
      // playback on transient route-load failures and let the visitor retry;
      // use the native navigation fallback when no song is playing.
      if (pip.dataset.playing !== 'true') {
        window.location.assign(targetUrl.href);
        return;
      }
      console.error('YAME route could not load while music was playing.', error);
      let notice = document.querySelector('[data-pip-navigation-notice]');
      if (!notice) {
        notice = document.createElement('button');
        notice.type = 'button';
        notice.dataset.pipNavigationNotice = '';
        notice.setAttribute('aria-live', 'polite');
        notice.textContent = 'PAGE DID NOT LOAD · TAP TO RETRY';
        notice.style.cssText = 'box-sizing:border-box;position:fixed;z-index:200;left:50%;top:50%;bottom:auto;transform:translate(-50%,-50%);padding:16px 21px;border:1px solid #3479d5;background:#0051ba;color:#ffe043;font:900 16px/1.2 Archivo,sans-serif;letter-spacing:.06em;cursor:pointer';
        document.body.append(notice);
      }
      notice.onclick = async () => {
        notice.hidden = true;
        try {
          await renderRoute(targetUrl, { push: true });
          notice.remove();
        } catch {
          notice.hidden = false;
        }
      };
    });
  });

  window.addEventListener('popstate', (event) => {
    if (!event.state?.yamePersistentPip) {
      window.location.reload();
      return;
    }
    const url = new URL(window.location.href);
    if (walkmanExcludedPath(url.pathname)) {
      window.location.reload();
      return;
    }
    renderRoute(url, { push: false, scrollY: Number(event.state.scrollY) || 0 }).catch(() => window.location.reload());
  });
}

