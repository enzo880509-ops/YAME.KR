function modalControls(overlay, bodyClass) {
  let previousFocus;
  let background = [];
  overlay.setAttribute('role', 'dialog');
  overlay.setAttribute('aria-modal', 'true');
  const focusable = () => [...overlay.querySelectorAll('button:not([disabled]), input:not([disabled]), a[href], [tabindex="0"]')]
    .filter((element) => !element.closest('[hidden], [inert]'));
  document.addEventListener('keydown', (event) => {
    if (overlay.hidden || event.key !== 'Tab') return;
    const controls = focusable();
    const first = controls[0];
    const last = controls[controls.length - 1];
    if (!first) return;
    if (!overlay.contains(document.activeElement) || (event.shiftKey && document.activeElement === first)) {
      event.preventDefault();
      (event.shiftKey ? last : first).focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  });
  return {
    open(initialFocus) {
      if (!overlay.hidden) return;
      previousFocus = document.activeElement;
      background = [...document.body.children].filter((element) => element !== overlay)
        .map((element) => [element, element.hasAttribute('inert')]);
      background.forEach(([element]) => element.setAttribute('inert', ''));
      overlay.hidden = false;
      document.body.classList.add(bodyClass);
      (initialFocus || focusable()[0])?.focus({ preventScroll: true });
    },
    close() {
      if (overlay.hidden) return;
      overlay.hidden = true;
      document.body.classList.remove(bodyClass);
      background.forEach(([element, wasInert]) => { if (!wasInert) element.removeAttribute('inert'); });
      background = [];
      if (previousFocus?.isConnected) previousFocus.focus({ preventScroll: true });
    }
  };
}

let galleryControls;

function openGalleryLightbox(src, alt) {
  let lightbox = document.querySelector('.gallery-lightbox');
  if (!lightbox) {
    lightbox = document.createElement('div');
    lightbox.className = 'gallery-lightbox';
    lightbox.hidden = true;
    lightbox.setAttribute('aria-label', 'Product photo gallery');
    lightbox.innerHTML = '<button type="button" class="gallery-lightbox__close" aria-label="Close image">×</button><button type="button" class="gallery-lightbox__prev" aria-label="Previous image">‹</button><img alt="" /><button type="button" class="gallery-lightbox__next" aria-label="Next image">›</button>';
    document.body.appendChild(lightbox);
    galleryControls = modalControls(lightbox, 'gallery-is-open');
    let touchStart = null;
    const close = () => { touchStart = null; galleryControls.close(); };
    const items = () => [...document.querySelectorAll('.article-gallery__item')];
    const showRelative = (step) => {
      const galleryItems = items();
      if (!galleryItems.length) return;
      const current = Math.max(0, galleryItems.findIndex((item) => item.dataset.gallerySrc === lightbox.dataset.currentSrc));
      const next = (current + step + galleryItems.length) % galleryItems.length;
      const item = galleryItems[next];
      openGalleryLightbox(item.dataset.gallerySrc, item.querySelector('img')?.alt || `Gallery image ${next + 1}`);
    };
    lightbox.querySelector('.gallery-lightbox__close').addEventListener('click', close);
    lightbox.querySelector('.gallery-lightbox__prev').addEventListener('click', () => showRelative(-1));
    lightbox.querySelector('.gallery-lightbox__next').addEventListener('click', () => showRelative(1));
    lightbox.addEventListener('click', (event) => { if (event.target === lightbox) close(); });
    lightbox.addEventListener('touchstart', (event) => {
      touchStart = null;
      if (event.touches.length !== 1 || event.target.closest('button')) return;
      const touch = event.touches[0];
      touchStart = { id: touch.identifier, x: touch.clientX, y: touch.clientY };
    }, { passive: true });
    lightbox.addEventListener('touchend', (event) => {
      if (!touchStart) return;
      const start = touchStart;
      touchStart = null;
      const touch = [...event.changedTouches].find((item) => item.identifier === start.id);
      if (!touch || event.touches.length) return;
      const dx = touch.clientX - start.x;
      const dy = touch.clientY - start.y;
      if (Math.abs(dx) > 45 && Math.abs(dx) > Math.abs(dy) * 1.25) showRelative(dx < 0 ? 1 : -1);
    }, { passive: true });
    lightbox.addEventListener('touchcancel', () => { touchStart = null; }, { passive: true });
    document.addEventListener('keydown', (event) => {
      if (lightbox.hidden || event.altKey || event.ctrlKey || event.metaKey) return;
      if (['Escape', 'ArrowLeft', 'ArrowRight'].includes(event.key)) event.preventDefault();
      if (event.key === 'Escape') close();
      else if (event.key === 'ArrowLeft') showRelative(-1);
      else if (event.key === 'ArrowRight') showRelative(1);
    });
  }
  lightbox.dataset.currentSrc = src;
  lightbox.querySelector('img').src = src;
  lightbox.querySelector('img').alt = alt;
  galleryControls.open(lightbox.querySelector('.gallery-lightbox__close'));
}

function setupReviewFilters() {
  const controls = [...document.querySelectorAll('[data-review-filter]')];
  const cards = [...document.querySelectorAll('[data-review-category]')];
  const count = document.querySelector('.review-count');
  const grid = document.querySelector('#review-grid');
  if (!controls.length || !cards.length || !grid) return;

  controls.forEach((control) => {
    control.addEventListener('click', () => {
      const category = control.dataset.reviewFilter;
      let visibleCount = 0;

      controls.forEach((button) => {
        button.setAttribute('aria-pressed', String(button === control));
      });

      cards.forEach((card) => {
        const visible = category === 'all' || card.dataset.reviewCategory === category;
        card.hidden = !visible;
        if (visible) visibleCount += 1;
      });

      grid.setAttribute('aria-label', category === 'all' ? 'All reviews' : `${category} reviews`);
      if (count) count.textContent = `${String(visibleCount).padStart(2, '0')} ${visibleCount === 1 ? 'review' : 'reviews'}`;
    });
  });
}

function updateStoryCards(language) {
  document.querySelectorAll('a[href*="story="]').forEach((card) => {
    const link = new URL(card.href, window.location.href);
    const slug = link.searchParams.get('story');
    const story = localizedStory(slug, language);
    if (!story) return;

    if (language === 'kr') link.searchParams.set('lang', 'kr');
    else link.searchParams.delete('lang');
    const page = document.body.dataset.page;
    if (page === 'review' || page === 'news') link.searchParams.set('from', page);
    else link.searchParams.delete('from');
    card.href = link.href;

    const title = card.querySelector('.feature-copy h3, .story-card__content .headline, .review-card__body h2');
    const subtitle = card.querySelector('.feature-copy > p:last-child, .story-card__content .summary, .review-card__body > p:not(.kicker)');
    if (title) { title.textContent = story.title; title.lang = language === 'kr' ? 'ko' : 'en'; }
    if (subtitle) { subtitle.textContent = story.dek; subtitle.lang = language === 'kr' ? 'ko' : 'en'; }
  });
}

